# 위험도가 높은 패턴 (정규식 패턴으로 확장 가능)
RISK_PATTERNS: List[str] = [
    r".*일체.*책임.*지지.*않",
    r".*어떠한.*경우에도.*이의.*제기.*불가",
    r".*계약.*해지.*불가",
    r".*일방적.*해지",
    r".*손해배상.*책임.*면제",
    r".*고객.*권리.*포기",
    r".*회사.*판단.*따라",
    r".*사전.*통지.*없이",
    r".*고객.*동의.*없이",
]


def contains_risk_keywords(text: str) -> bool:
    """텍스트에 위험 키워드가 포함되어 있는지 확인"""
    text_lower = text.lower()
    return any(keyword in text_lower for keyword in RISK_KEYWORDS)


def get_matched_keywords(text: str) -> List[str]:
    """텍스트에서 매칭된 위험 키워드 리스트 반환"""
    text_lower = text.lower()
    matched = [keyword for keyword in RISK_KEYWORDS if keyword in text_lower]
    return matched



